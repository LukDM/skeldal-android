package cz.gates.skeldal.settings

import java.io.File

/**
 * Generates the skeldal.ini used by the engine on Android. This file belongs to the app
 * (filesDir/skeldal.ini); the skeldal.ini of the user's PC installation is never imported or changed.
 * Keys are the ones documented in the repository's skeldal.ini.
 */
object GameConfigWriter {

    fun render(settings: GameSettings, gameDir: File, savesDir: File): String = buildString {
        append("# Generated by the Android launcher - changes are overwritten on every start.\n")
        append("[paths]\n")
        append("root=").append(gameDir.absolutePath).append('\n')
        append("savegame=").append(savesDir.absolutePath).append('\n')
        append('\n')
        append("[video]\n")
        append("fullscreen=").append(onOff(settings.fullscreen)).append('\n')
        append("scaling=").append(settings.scaling.ini).append('\n')
        append("aspect_ratio=4:3\n")
        append("picture_scale=").append(settings.pictureScale.coerceIn(50, 100)).append('\n')
        append("scale_quality=").append(if (settings.smoothScaling) "linear" else "nearest").append('\n')
        append("crt_filter=").append(settings.crtFilter.ini).append('\n')
        append("vsync=").append(onOff(settings.vsync)).append('\n')
        append("video_scanlines=").append(onOff(settings.videoScanlines)).append('\n')
        append("composer=auto\n")
        // pause also when e.g. the notification shade covers the game (background pause is always on)
        append("pause_on_focus_loss=on\n")
        append("autosave_on_background=").append(onOff(settings.autosaveOnBackground)).append('\n')
        append('\n')
        append("[game]\n")
        append("always_minimap=").append(onOff(settings.alwaysMinimap)).append('\n')
        append("show_enemy_lives=").append(settings.enemyLives.ini).append('\n')
        append("overlay_map_dim=").append(onOff(settings.overlayMapDim)).append('\n')
        append("game_speed=").append(settings.gameSpeed.ini).append('\n')
        append('\n')
        append("[controller]\n")
        append("enabled=").append(onOff(settings.controllerEnabled)).append('\n')
        append("swap_sticks=").append(onOff(settings.swapSticks)).append('\n')
        append("slow_cursor_with_mod=").append(onOff(settings.slowCursorWithMod)).append('\n')
        val map = settings.controllerMapping
        for (i in 0 until ControllerMapping.BUTTON_COUNT) {
            append("button").append(i).append('=').append(map.normal[i]).append('\n')
            append("mod+button").append(i).append('=').append(map.withMod[i]).append('\n')
        }
        // learned extra buttons (M1, M2, ...): same action with and without the modifier
        for ((code, slot) in ExtraButtons.slots(settings.extraButtons)) {
            val action = settings.extraButtons.getValue(code)
            val n = ControllerMapping.FIRST_EXTRA + slot
            append("button").append(n).append('=').append(action).append('\n')
            append("mod+button").append(n).append('=').append(action).append('\n')
        }
    }

    /** Writes atomically so the game never reads a half-written file. */
    fun write(target: File, settings: GameSettings, gameDir: File, savesDir: File) {
        savesDir.mkdirs()
        val tmp = File(target.path + ".tmp")
        tmp.writeText(render(settings, gameDir, savesDir))
        if (!tmp.renameTo(target)) {
            target.delete()
            if (!tmp.renameTo(target)) throw java.io.IOException("Cannot write ${target.path}")
        }
    }

    private fun onOff(b: Boolean) = if (b) "on" else "off"
}
